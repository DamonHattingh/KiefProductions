using KiefProductions.Data;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using QuestPDF.Infrastructure;

var builder = WebApplication.CreateBuilder(args);

// ?? QuestPDF licence (Community = free) ??????????????????????????????????????
QuestPDF.Settings.License = LicenseType.Community;

// ?? Database ??????????????????????????????????????????????????????????????????
var connectionString = builder.Configuration.GetConnectionString("DefaultConnection")
    ?? throw new InvalidOperationException("Connection string 'DefaultConnection' not found.");

builder.Services.AddDbContext<ApplicationDbContext>(options =>
    options.UseSqlServer(connectionString));

builder.Services.AddDatabaseDeveloperPageExceptionFilter();

// ?? Identity ??????????????????????????????????????????????????????????????????
builder.Services.AddDefaultIdentity<IdentityUser>(options =>
{
    options.SignIn.RequireConfirmedAccount = false;
    options.Password.RequireDigit = true;
    options.Password.RequiredLength = 8;
    options.Password.RequireNonAlphanumeric = false;
    options.Password.RequireUppercase = true;
})
.AddRoles<IdentityRole>()
.AddEntityFrameworkStores<ApplicationDbContext>();

builder.Services.AddHttpContextAccessor();
builder.Services.AddScoped<KiefProductions.Services.PuppeteerPdfService>();
builder.Services.AddScoped<KiefProductions.Services.RazorViewRenderer>();
builder.Services.AddScoped<KiefProductions.Services.VendorDocumentExtractionService>();

// ?? MVC ???????????????????????????????????????????????????????????????????????
builder.Services.AddControllersWithViews();
builder.Services.AddRazorPages();

var app = builder.Build();

// ?? Middleware pipeline ???????????????????????????????????????????????????????
if (app.Environment.IsDevelopment())
{
    app.UseMigrationsEndPoint();
}
else
{
    app.UseExceptionHandler("/Home/Error");
    app.UseHsts();
}

app.UseHttpsRedirection();
app.UseStaticFiles();
app.UseRouting();
app.UseAuthentication();
app.UseAuthorization();

app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");

app.MapRazorPages();

// ?? Seed roles and default admin on startup ???????????????????????????????????
using (var scope = app.Services.CreateScope())
{
    var roleManager = scope.ServiceProvider.GetRequiredService<RoleManager<IdentityRole>>();
    var userManager = scope.ServiceProvider.GetRequiredService<UserManager<IdentityUser>>();

    string[] roles = ["Admin", "Staff"];
    foreach (var role in roles)
    {
        if (!await roleManager.RoleExistsAsync(role))
            await roleManager.CreateAsync(new IdentityRole(role));
    }

    // Default admin account � change password after first login
    if (!userManager.Users.Any())
    {
        var admin = new IdentityUser
        {
            UserName = "admin@kiefproductions.co.za",
            Email = "admin@kiefproductions.co.za",
            EmailConfirmed = true
        };

        var result = await userManager.CreateAsync(admin, "Admin@1234");
        if (result.Succeeded)
            await userManager.AddToRoleAsync(admin, "Admin");
    }
}

app.Run();